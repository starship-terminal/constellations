#!/usr/bin/env python3
"""Write the Brief section of every package README: the page to read before designing in its style.

    python3 tools/brief.py            rewrite every package's Brief
    python3 tools/brief.py --check    fail if any Brief differs from a fresh write

A package's Brief sits in its README between the `brief:start` and `brief:end` markers,
right after the file table and before `## Health`. Every line of it comes from data the
package already has; nothing in it is written by hand:

| Part | Comes from |
|---|---|
| Principles | The bold lead of each rule in the README's "Do and don't" list (its first sentence when it has none), read as tools/grade.py's K2 check reads it |
| Using tokens | The catalog's preview swatches and fonts, resolved in the tokens file, for every theme palette tools/grade.py checks; then the scale counts DESIGN.md holds |
| Using components | Which of components.md, patterns.md, components/crops/ and style-guide.html exist, with the number of crop images |
| Accessibility | The same contrast pairs tools/grade.py's F15 check measures, then the token paths that name focus, each with its docs/EVIDENCE.md label when that says it was not measured |

`make brief` writes it, `make design-md` runs this first, and `make check` runs
`--check`. The section never reaches DESIGN.md, which copies README sections by heading
and has none that matches "Brief".

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalog  # noqa: E402
import grade  # noqa: E402
from health import cell  # noqa: E402

ROOT = catalog.ROOT
NOTE = "Generated by tools/brief.py from catalog.json, the tokens file and this README; `make brief` rewrites it. Do not edit."
BRIEF = re.compile(r"^## Brief\n.*?^<!-- brief:end -->\n", re.M | re.S)
NEED = 4.5
FOCUS_LIMIT = 4
PAIRS = (("text", "page"), ("text", "surface"), ("muted", "page"), ("muted", "surface"))
BOLD_LEAD = re.compile(r"^\*\*(.+?)\*\*")
FIRST_SENTENCE = re.compile(r"^(.+?[.!?])(?=\s|$)")


def slug(heading: str) -> str:
    """The anchor GitHub and Python-Markdown give a heading: lower case, punctuation
    dropped, spaces as hyphens."""
    return re.sub(r"\s+", "-", re.sub(r"[^\w\s-]", "", heading.strip().lower()))


def lead(rule: str) -> str:
    """A rule's bold lead sentence, or its first sentence when it has no bold lead."""
    m = BOLD_LEAD.match(rule.strip())
    if m:
        return m.group(1).strip()
    m = FIRST_SENTENCE.match(rule.strip())
    return (m.group(1) if m else rule).strip()


def principles(readme: str) -> list[str]:
    found = grade.do_and_dont(readme)
    lines = ["### Principles", ""]
    if found is None:
        return lines + ["The README has no \"Do and don't\" section, so this package states no principles.", ""]
    heading, rules = found
    if not rules:
        return lines + [f"The README's [{heading}](#{slug(heading)}) section lists no rules.", ""]
    lines += [f"{i}. {lead(rule)}" for i, rule in enumerate(rules, 1)]
    return lines + ["", f"Each rule links the screenshot or crop that shows it, under [{heading}](#{slug(heading)}).", ""]


def _value(raw) -> str:
    """One resolved value as text: CSS where there is a CSS form, else the raw value."""
    if raw is None or catalog._unresolved(raw):
        return "unresolved"
    css = catalog.css_value(raw)
    return css if css is not None else str(raw)


def _fallbacks(stack: str) -> str:
    n = len([f for f in stack.split(",") if f.strip()]) - 1
    return f"then {n} fallback{'s' if n != 1 else ''}" if n > 0 else "with no fallback"


def using_tokens(system: dict, palettes: dict, sources: dict, front: dict) -> list[str]:
    res = catalog.resolver_for(system["tokens"])
    themes = list(palettes)
    lines = ["### Using tokens", ""]
    if themes:
        lines += ["| Role | " + " | ".join(cell(t) for t in themes) + " |", "|---" * (len(themes) + 1) + "|"]
        for role in catalog.SWATCH_ROLES:
            cells = []
            for theme in themes:
                path = palettes[theme].get(role)
                cells.append(f"{cell(_value(res.lookup(path)))} `{cell(path)}`" if path else "no swatch")
            lines.append(f"| {role} | " + " | ".join(cells) + " |")
        lines.append("")
    else:
        lines += ["The catalog names no swatches for this package.", ""]
    fonts = catalog.fonts(system)
    text = ("Fonts: " + "; ".join(f"`{f['token']}` is {f['family']}, {_fallbacks(f['stack'])}" for f in fonts) + "."
            if fonts else "Fonts: the catalog preview names none.")
    where = lambda group: " and ".join(f"`{p.rstrip('.')}`" for p in sources[group])
    scales = []
    for group, noun in (("typography", "type style"), ("rounded", "radius step"), ("spacing", "spacing step")):
        n = len(front.get(group, {}))
        scales.append(f"{n} {noun}{'s' if n != 1 else ''} ({where(group)})" if n else f"no {noun}s under {where(group)}")
    text += f" Scales, counted as [DESIGN.md](DESIGN.md) holds them: {', '.join(scales)}."
    return lines + [text, ""]


def _count(folder: Path, exts: set[str]) -> int:
    return sum(1 for p in folder.rglob("*") if p.is_file() and p.suffix.lower() in exts)


def using_components(system: dict) -> list[str]:
    pkg = ROOT / "systems" / system["slug"]
    gaps = system.get("layoutGaps", {})
    parts = []
    for name, what in (("components.md", "the component inventory"), ("patterns.md", "how components combine into screens")):
        if (pkg / name).is_file():
            parts.append(f"[{name}]({name}) for {what}")
        elif name in gaps:
            parts.append(f"no {name} ({gaps[name].rstrip('.')})")
        else:
            parts.append(f"no {name}")
    comps = pkg / "components"
    if (comps / "crops").is_dir():
        n = _count(comps / "crops", catalog.COMPONENT_EXT)
        parts.append(f"{n} element crop{'s' if n != 1 else ''} in [components/crops/](components/crops)")
    if comps.is_dir():
        other = sum(1 for p in comps.rglob("*") if p.is_file() and p.suffix.lower() in catalog.COMPONENT_EXT
                    and (comps / "crops") not in p.parents)
        if other:
            parts.append(f"{other} other image{'s' if other != 1 else ''} in [components/](components)")
    elif "components/" in gaps:
        parts.append(f"no components/ ({gaps['components/'].rstrip('.')})")
    else:
        parts.append("no components/")
    parts.append("[style-guide.html](style-guide.html), which renders every token and the main components")
    return ["### Using components", "", "Read " + "; ".join(parts) + ".", ""]


def _pair(row: dict | None) -> str:
    if row is None:
        return "no swatch"
    if row["ratio"] is None:
        return {"unchecked": "not checked (translucent)", "missing": "no colour"}.get(row["status"], row["status"])
    return f"{row['ratio']:.2f}:1 {row['status']}"


# docs/EVIDENCE.md's labels. A focus token labelled one of NOT_MEASURED is named
# with its label, so a sampled, reconstructed or uncaptured focus value is never
# read as a measurement. Derived values are worked out from measured ones, so
# they are listed plainly like Measured and unlabelled tokens.
LABELS = ("Measured", "Derived", "Sampled", "Observed", "Reconstruction", "Not captured")
NOT_MEASURED = ("Sampled", "Observed", "Reconstruction", "Not captured")


def token_objects(tokens: dict) -> dict[str, dict]:
    """Map catalog.flatten's dotted paths to their token objects, by the same walk, so a
    key that itself holds a dot (`input.error.focus`) lands on the same path."""
    found: dict[str, dict] = {}

    def walk(node, path):
        if not isinstance(node, dict):
            return
        if "$value" in node or ("value" in node and not isinstance(node["value"], dict)):
            found[".".join(path)] = node
            return
        for key, child in node.items():
            if not key.startswith("$"):
                walk(child, path + [key])

    walk(tokens, [])
    return found


def evidence(token) -> str | None:
    """The docs/EVIDENCE.md label a token carries: `$extensions.source.evidence`,
    `$extensions.evidence`, or a `$extensions.source` sentence that opens with a
    label ("Reconstruction: entered by hand ..."). None when it names none."""
    ext = token.get("$extensions") if isinstance(token, dict) else None
    if not isinstance(ext, dict):
        return None
    src = ext.get("source")
    for raw in (src.get("evidence") if isinstance(src, dict) else None, ext.get("evidence"),
                src if isinstance(src, str) else None):
        if isinstance(raw, str):
            for label in LABELS:
                if re.match(re.escape(label) + r"\b", raw.strip(), re.I):
                    return label
    return None


def focus_tokens(system: dict, theme: str | None) -> str:
    res = catalog.resolver_for(system["tokens"])
    tokens = token_objects(json.loads((ROOT / system["tokens"]).read_text()))
    # A base token (`shadow.focus`, `focusRing.width`) before a variant of it (`shadow.focus-danger`).
    variant = lambda p: bool(re.search(r"focus[a-z]*[-_][a-z]", p.split(".")[-1], re.I))
    paths = sorted((p for p in res.flat if "focus" in p.lower()),
                   key=lambda p: (variant(p), len(p), p))[:FOCUS_LIMIT]
    if not paths:
        return "Focus: no focus tokens (no token path contains \"focus\")."
    shown = []
    for path in paths:
        raw = res.final(path)
        if (raw is None or catalog._unresolved(raw)) and theme:
            raw = res.final(path, theme=theme)
        label = evidence(tokens.get(path))
        shown.append(f"`{path}` {_value(raw)}" + (f" ({label}, not measured)" if label in NOT_MEASURED else ""))
    return "Focus tokens: " + "; ".join(shown) + "."


def accessibility(system: dict, rows: list[dict], palettes: dict, unchecked: list[str]) -> list[str]:
    lines = ["### Accessibility", ""]
    if palettes:
        by = {(r["theme"], r["role"], r["bgRole"]): r for r in rows}
        lines += ["| Theme | " + " | ".join(f"{fg} on {bg}" for fg, bg in PAIRS) + " |", "|---" * (len(PAIRS) + 1) + "|"]
        for theme in palettes:
            lines.append(f"| {cell(theme)} | " + " | ".join(_pair(by.get((theme, fg, bg))) for fg, bg in PAIRS) + " |")
        lines.append("")
        passed = sum(1 for r in rows if r["status"] == "pass")
        text = f"{passed} of {len(rows)} pairs pass {NEED}:1 (WCAG AA for body text), the pairs the scorecard's F15 check grades."
    else:
        text = "No theme has a palette, so no contrast was checked."
    if unchecked:
        text += f" Not checked, no palette: {', '.join(unchecked)}."
    return lines + [text + " " + focus_tokens(system, next(iter(palettes), None)), ""]


def section(system: dict) -> str:
    """The README's Brief section for one catalog entry."""
    pkg = ROOT / "systems" / system["slug"]
    readme = (pkg / "README.md").read_text()
    tokens_rel = Path(os.path.relpath(ROOT / system["tokens"], pkg)).as_posix()
    rows, palettes, unchecked = grade.contrast_rows(system)
    data = catalog.design_md_tokens(system)
    lines = ["## Brief", "", f"<!-- brief:start. {NOTE} -->", "",
             f"Read this before designing in this style. Take every value from [{tokens_rel}]({tokens_rel}), "
             f"never from the screenshots; `python3 tools/catalog.py export {system['slug']}` prints them all "
             "with aliases resolved.", ""]
    lines += principles(readme)
    lines += using_tokens(system, palettes, data["sources"], data["front"])
    lines += using_components(system)
    lines += accessibility(system, rows, palettes, unchecked)
    lines += ["<!-- brief:end -->", ""]
    return "\n".join(lines)


def with_section(readme: str, brief: str) -> str:
    """The README with its Brief replaced in place, or inserted before `## Health`, or
    before the first `##` when there is no Health section."""
    if BRIEF.search(readme):
        return BRIEF.sub(lambda _: brief, readme, count=1)
    at = re.search(r"^## Health\n", readme, re.M) or re.search(r"^## ", readme, re.M)
    if not at:
        return readme.rstrip("\n") + "\n\n" + brief
    return readme[:at.start()] + brief + "\n" + readme[at.start():]


def expected(systems: list[dict]) -> dict[Path, str]:
    out = {}
    for s in systems:
        path = ROOT / "systems" / s["slug"] / "README.md"
        if path.is_file():
            out[path] = with_section(path.read_text(), section(s))
    return out


def problems(systems: list[dict]) -> list[str]:
    return [f"{path.relative_to(ROOT)}: Brief is stale; run `make brief`"
            for path, text in expected(systems).items() if path.read_text() != text]


def write(systems: list[dict]) -> list[Path]:
    changed = []
    for path, text in expected(systems).items():
        if path.read_text() != text:
            catalog.atomic_write(path, text)
            changed.append(path)
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a Brief is stale")
    args = parser.parse_args()
    systems = catalog.load_catalog()["systems"]
    if args.check:
        found = problems(systems)
        if found:
            sys.exit("\n".join(found))
        print("brief current")
        return
    changed = write(systems)
    print("\n".join(f"wrote {p.relative_to(ROOT)}" for p in changed) or "brief already current")


if __name__ == "__main__":
    main()
