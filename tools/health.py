#!/usr/bin/env python3
"""Write each package's Health section and the root README's catalog table.

    python3 tools/health.py            rewrite them from the newest scorecard snapshot
    python3 tools/health.py --check    fail if any of them differs from a fresh write

A package's Health section sits in its README between the `health:start` and
`health:end` markers, as the first `##` section. It says how many scorecard criteria the
package meets, lists every criterion it only partly meets or misses with the reviewer's
evidence, flags a capture newer than the last review, and lists the standard layout parts
the package lacks (docs/PACKAGE.md). The root README's catalog table, between the
`catalog:start` and `catalog:end` markers, puts the same counts beside every package.

`make grade` runs this after it writes a snapshot, and `make check` runs `--check`, so a
README never shows grades older than the scorecard. Nothing in the sections depends on the
snapshot's date, so re-grading a package rewrites only the READMEs whose grades changed.

Standard library only.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalog  # noqa: E402
import scorecard  # noqa: E402

ROOT = catalog.ROOT
NOTE = "Generated by tools/health.py from the newest scorecard snapshot; `make grade` rewrites it. Do not edit."
HEALTH = re.compile(r"^## Health\n.*?^<!-- health:end -->\n", re.M | re.S)
TABLE = re.compile(r"^<!-- catalog:start.*?^<!-- catalog:end -->\n", re.M | re.S)
WORST_FIRST = ("missing", "partly")


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def tally(grades: dict) -> dict:
    out = {g: 0 for g in scorecard.GRADES}
    for g in grades.values():
        out[g["grade"]] += 1
    return out


def summary(n: dict) -> str:
    graded = sum(n.values()) - n["na"]
    return f"{n['meets']} of {graded} met, {n['partly']} partly, {n['missing']} missing"


def reviewed(audit: dict, graded: dict) -> str:
    return graded.get("reviewed", audit.get("base", audit["date"]))


def layout_line(system: dict) -> str:
    slug = system["slug"]
    missing, unlisted = catalog.layout_gaps(slug)
    why = system.get("layoutGaps", {})
    if not missing and not unlisted:
        return "Layout: every standard part is here and in the file table ([docs/PACKAGE.md](../../docs/PACKAGE.md))."
    parts = []
    if missing:
        parts.append("no " + ", ".join(f"`{m}`" + (f" ({why[m].rstrip('.')})" if why.get(m) else "") for m in missing))
    if unlisted:
        parts.append("not in the file table above: " + ", ".join(f"`{u}`" for u in unlisted))
    return f"Layout ([docs/PACKAGE.md](../../docs/PACKAGE.md)): {'; '.join(parts)}."


def package_section(criteria: dict, audit: dict, system: dict) -> str:
    """The README's Health section for one catalog entry."""
    slug = system["slug"]
    graded = next((s for s in audit["systems"] if s["slug"] == slug), None)
    lines = ["## Health", "", f"<!-- health:start. {NOTE} -->", ""]
    if graded is None:
        lines += ["Not graded yet: no scorecard snapshot reviews this package. Review it against "
                  "[scorecard/criteria.json](../../scorecard/criteria.json) in the wording for its platform "
                  "(`python3 tools/grade.py --criteria " + slug + "` prints it) and merge the grades with "
                  "`python3 tools/grade.py --write --review " + slug + "=<grades.json>`.", ""]
    else:
        n = tally(graded["grades"])
        na = [cid for cid, g in graded["grades"].items() if g["grade"] == "na"]
        when = reviewed(audit, graded)
        text = (f"Scorecard: **{summary(n)}**" + (f"; {', '.join(na)} do not apply to a capture" if na else "")
                + f". Grades last reviewed {when}, package captured {system.get('captured', 'on an unknown date')}.")
        if system.get("captured", "") > when:
            text += " **Re-review due**: the capture is newer than the review."
        lines += [text + " Every grade with its evidence is on the Scorecard page of `make serve`.", ""]
        titles = {c["id"]: c["title"] for c in criteria["criteria"]}
        order = [c["id"] for c in criteria["criteria"]]
        open_ = sorted((cid for cid, g in graded["grades"].items() if g["grade"] in WORST_FIRST),
                       key=lambda cid: (WORST_FIRST.index(graded["grades"][cid]["grade"]), order.index(cid)))
        if open_:
            lines += ["| Open | Grade | Evidence |", "|---|---|---|"]
            for cid in open_:
                g = graded["grades"][cid]
                lines.append(f"| {cid} {cell(titles.get(cid, ''))} | {scorecard.GRADES[g['grade']][1]} "
                             f"| {cell(g['evidence'])} |")
            lines.append("")
        else:
            lines += ["Every gradable criterion is met.", ""]
    lines += [layout_line(system), "", "<!-- health:end -->", ""]
    return "\n".join(lines)


def with_section(readme: str, section: str) -> str:
    """The README with its Health section replaced, or inserted before the first `##`."""
    if HEALTH.search(readme):
        return HEALTH.sub(lambda _: section, readme, count=1)
    first = re.search(r"^## ", readme, re.M)
    if not first:
        return readme.rstrip("\n") + "\n\n" + section
    return readme[:first.start()] + section + "\n" + readme[first.start():]


def catalog_table(audit: dict, systems: list[dict]) -> str:
    """The root README's catalog table, ranked by the scorecard as its overview is."""
    graded = {s["slug"]: s for s in audit["systems"]}
    rank = {s["slug"]: i for i, s in enumerate(scorecard.ranked(audit["systems"]))}
    rows = sorted(systems, key=lambda s: (rank.get(s["slug"], len(rank)), s["slug"]))
    lines = [f"<!-- catalog:start. {NOTE} -->", "",
             "| Package | Good for | Captured | Themes | Health | Layout gaps |", "|---|---|---|---|---|---|"]
    for s in rows:
        slug = s["slug"]
        g = graded.get(slug)
        health = summary(tally(g["grades"])) if g else "not graded yet"
        if g and s.get("captured", "") > reviewed(audit, g):
            health += ", re-review due"
        missing, _ = catalog.layout_gaps(slug)
        gaps = ", ".join(f"`{m}`" for m in missing) or "none"
        lines.append(f"| [{slug}](systems/{slug}/README.md) | {cell(s.get('goodFor', ''))} | {s.get('captured', '')} "
                     f"| {', '.join(s.get('themes', []))} | {health} | {gaps} |")
    lines += ["", "<!-- catalog:end -->", ""]
    return "\n".join(lines)


def expected(criteria: dict, audit: dict, systems: list[dict]) -> dict[Path, str]:
    """Every README this script owns a part of, as it should read now."""
    out = {}
    for s in systems:
        path = ROOT / "systems" / s["slug"] / "README.md"
        if path.is_file():
            out[path] = with_section(path.read_text(), package_section(criteria, audit, s))
    root = ROOT / "README.md"
    text = root.read_text()
    if not TABLE.search(text):
        sys.exit("README.md has no <!-- catalog:start --> ... <!-- catalog:end --> block to fill")
    out[root] = TABLE.sub(lambda _: catalog_table(audit, systems), text, count=1)
    return out


def problems(criteria: dict, audit: dict, systems: list[dict]) -> list[str]:
    return [f"{path.relative_to(ROOT)}: Health is stale; run `python3 tools/health.py`"
            for path, text in expected(criteria, audit, systems).items() if path.read_text() != text]


def write(criteria: dict, audit: dict, systems: list[dict]) -> list[Path]:
    changed = []
    for path, text in expected(criteria, audit, systems).items():
        if path.read_text() != text:
            path.write_text(text)
            changed.append(path)
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a Health section or the catalog table is stale")
    args = parser.parse_args()
    criteria, audits = scorecard.load()
    systems = catalog.load_catalog()["systems"]
    if args.check:
        found = problems(criteria, audits[-1], systems)
        if found:
            sys.exit("\n".join(found))
        print("health current")
        return
    changed = write(criteria, audits[-1], systems)
    print("\n".join(f"wrote {p.relative_to(ROOT)}" for p in changed) or "health already current")


if __name__ == "__main__":
    main()
