export async function patch(context) {
  await context.addInitScript(() => {
    Object.defineProperty(navigator, 'webdriver', { get: () => undefined });
    try { window.__captureDPR = window.devicePixelRatio; } catch { /* read-only */ }
  });
}

export async function launch({ width = 1440, height = 900, mobile = false } = {}) {
  const browser = await chromium.launch();
  const context = await browser.newContext(mobile
    ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, userAgent: UA_MOBILE, isMobile: true, hasTouch: true, locale: 'en-US' }
    : { viewport: { width, height }, deviceScaleFactor: 1, userAgent: UA, locale: 'en-US', reducedMotion: 'reduce' });
  await patch(context);
  return { browser, context };
}

export async function clearChallenge(page, { tries = 8, step = 1500 } = {}) {
  for (let i = 0; i < tries; i++) {
    const s = await page.evaluate(() => ({
      title: document.title,
      body: (document.body && document.body.innerText || '').slice(0, 400),
    })).catch(() => ({ title: '', body: '' }));
    const challenging = /just a moment/i.test(s.title)
      || /performing security verification|verify you are human|verifying you are human|checking your browser/i.test(s.body);
    if (!challenging && s.body.length > 40) return true;
    await page.waitForTimeout(step);
  }
  return false;
}

// Hide the OneTrust banner. Never click Accept, Reject, or Cookie Settings:
// those buttons POST a consent choice. Hiding is display:none only.
export async function closePromo(page) {
  await page.addStyleTag({
    content: '#onetrust-consent-sdk, #onetrust-banner-sdk, #onetrust-pc-sdk, .onetrust-pc-dark-filter, #ot-sdk-btn-floating { display: none !important; visibility: hidden !important; }',
  }).catch(() => {});
  await page.evaluate(() => {
    for (const id of ['onetrust-consent-sdk', 'onetrust-banner-sdk', 'onetrust-pc-sdk']) {
      const el = document.getElementById(id);
      if (el) el.style.setProperty('display', 'none', 'important');
    }
    document.documentElement.classList.remove('ot-overflow-hidden');
    document.body && document.body.style.removeProperty('overflow');
  }).catch(() => {});
  return true;
}

export async function open(page, url, { wait = 4000, promo = 'close' } = {}) {
  // A failed navigation or a bot check that never clears is not the product: throw, as the kit's
  // open() does, rather than measure the interstitial into raw/.
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90000 });
  if (!(await clearChallenge(page))) throw new Error('challenge did not clear: ' + url);
  await page.waitForTimeout(wait);
  if (promo === 'close') await closePromo(page);
}

