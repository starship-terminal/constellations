export async function patch(context) {
  await context.addInitScript(() => {
    // automation is not hidden: the webdriver flag stays as Chromium sets it (bot check: recorded as a boundary, not bypassed)
    // lemni.com/signin overwrites devicePixelRatio to 1 while the renderer
    // still paints at the context scale. Keep the launch-time value so the
    // screenshot sidecar can check the PNG against the real scale.
    try { window.__captureDPR = window.devicePixelRatio; } catch { /* read-only */ }
  });
}

export async function launch({ width = 1440, height = 900, mobile = false } = {}) {
  const browser = await chromium.launch();
  const context = await browser.newContext(mobile
    ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, userAgent: UA_MOBILE, isMobile: true, hasTouch: true, locale: 'en-US' }
    : { viewport: { width, height }, deviceScaleFactor: 2, userAgent: UA, locale: 'en-US', reducedMotion: 'no-preference' });
  await patch(context);
  return { browser, context };
}

// Hide (never click) a cookie, consent or promo overlay. Lemni's public
// pages did not mount one on 2026-11-18; this still runs before every shot.
export async function closePromo(page) {
  for (let i = 0; i < 3; i++) {
    const hit = await page.evaluate(() => {
      let n = 0;
      for (const x of document.querySelectorAll('div, section, aside, [role="dialog"], [role="alertdialog"]')) {
        const t = x.innerText || '';
        const r = x.getBoundingClientRect();
        const cs = getComputedStyle(x);
        const overlay = (cs.position === 'fixed' || cs.position === 'sticky')
          && r.width > 80 && r.height > 40 && r.height < innerHeight * 0.85
          && /cookie|we value your privacy|consent|accept all|reject all|manage preferences/i.test(t);
        if (!overlay) continue;
        x.setAttribute('data-m-hidden-overlay', '1');
        x.style.setProperty('display', 'none', 'important');
        n++;
      }
      return n;
    }).catch(() => 0);
    if (hit) return true;
    await page.waitForTimeout(400);
  }
  return false;
}

export async function clearChallenge(page, { tries = 8, step = 1500 } = {}) {
  for (let i = 0; i < tries; i++) {
    const s = await page.evaluate(() => ({
      title: document.title,
      body: (document.body && document.body.innerText || '').slice(0, 500),
    })).catch(() => ({ title: '', body: '' }));
    const challenging = /just a moment/i.test(s.title)
      || /performing security verification|verify you are human|verifying you are human|checking your browser/i.test(s.body);
    if (!challenging && s.body.length > 30) return true;
    await page.waitForTimeout(step);
  }
  return false;
}

export async function open(page, url, { wait = 5000 } = {}) {
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForTimeout(wait);
  await closePromo(page);
}

