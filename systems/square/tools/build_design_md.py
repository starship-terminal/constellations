#!/usr/bin/env python3
"""Write DESIGN.md from tokens.json without editing catalog.json.

This follows the mapping in docs/PACKAGE.md: the light theme's semantic
colours, core typography, radius and spacing. It is regenerated, not edited.
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((HERE / "tokens.json").read_text())

ROLES = {
    "primary": "accent",
    "neutral": "page",
    "surface": "surface",
    "on-surface": "text",
    "on-surface-variant": "muted",
    "outline": "border",
}


def flat(node, prefix=""):
    out = {}
    for k, v in node.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" in v:
            out[prefix + k] = v
        elif isinstance(v, dict):
            out.update(flat(v, prefix + k + "."))
    return out


def colour(v):
    if isinstance(v, str) and (v.startswith("#") or v.startswith("rgba(")):
        return v
    return None


def dim(v):
    if isinstance(v, str) and re.fullmatch(r"-?\d+(\.\d+)?(px|rem|em)", v):
        return v
    return None


colors = {}
for name, role in ROLES.items():
    colors[name] = T["light"][role]["$value"]
for path, tok in flat(T["light"]).items():
    if tok.get("$type") != "color":
        continue
    colors.setdefault(path.replace(".", "-"), tok["$value"])

type_lines = []
for name, tok in flat(T["core"].get("typography", {})).items():
    if tok.get("$type") != "typography":
        continue
    v = tok["$value"]
    family = v["fontFamily"]
    if isinstance(family, str) and family.startswith("{fontFamily."):
        key = family.strip("{}").split(".")[-1]
        family = T["core"]["fontFamily"][key]["$value"]
    type_lines.append(
        f"  {name}:\n    fontFamily: {json.dumps(family)}\n    fontSize: {v['fontSize']}\n    fontWeight: {v['fontWeight']}\n    lineHeight: {v['lineHeight']}"
    )

rounded = []
for name, tok in flat(T["core"].get("radius", {})).items():
    d = dim(tok.get("$value"))
    if d:
        rounded.append(f"  {name}: {d}")

spacing = []
for name, tok in sorted(flat(T["core"].get("spacing", {})).items(), key=lambda kv: float(kv[0]) if kv[0].replace('.', '', 1).isdigit() else 0):
    d = dim(tok.get("$value"))
    if d:
        spacing.append(f"  {name}: {d}")

color_yaml = "\n".join(f"  {k}: {json.dumps(v)}" for k, v in colors.items())
body = f"""---
# Generated by systems/square/tools/build_design_md.py from tokens.json and README.md. Do not edit.
# Source of truth: tokens.json. DESIGN.md spec version alpha.
# catalog.json was not edited for this capture, so this file is written by the package builder.
version: "alpha"
name: "Square"
description: "Square public marketing site: payments, hardware, pricing and business-type pages"
colors:
{color_yaml}
typography:
{chr(10).join(type_lines)}
rounded:
{chr(10).join(rounded)}
spacing:
{chr(10).join(spacing)}
components:
  button:
    backgroundColor: "{T['light']['accent']['$value']}"
    textColor: "{T['light']['onAccent']['$value']}"
    rounded: "{T['core']['radius']['button']['$value']}"
---

# Square

Generated from [tokens.json](tokens.json) and [README.md](README.md) by the package builder. Do not edit this file. Change the tokens through the builders, then run `python3 tools/build_design_md.py`.

It follows the DESIGN.md spec, version alpha. That format has no themes and no per-value provenance, so this file holds the light theme. Dark tokens stay in tokens.json. The public homepage paints light. Dark values in tokens.json are declared `data-color-mode=dark` custom properties, not a live dark screenshot.

## Overview

Square's public site is a light marketing system: white page, black ink, pill actions, Square Sans for UI, Square Sans Display and Exact Block for headlines.

## Colors

Role colours are the light semantic set: page `{T['light']['page']['$value']}`, surface `{T['light']['surface']['$value']}`, text `{T['light']['text']['$value']}`, muted `{T['light']['muted']['$value']}`, accent `{T['light']['accent']['$value']}`, border `{T['light']['border']['$value']}`.

## Typography

Display is Square Sans Display. Headlines on the homepage also use Exact Block. Body is Square Sans Text.

## Layout

Spacing steps are the `--space-*` scale, converted from rem at 1rem = 10px (body 1.6rem computed as 16px). Breakpoints were read but are not a DESIGN.md spacing form.

## Elevation

No shadow tokens were promoted. Elevation on the public site was not measured as a token. Not captured.

## Components

The button specimen uses the accent fill, on-accent text, and the button radius token.

## Do's and Don'ts

See README.md. Do not invent a second accent. Do not treat the declared dark tokens as a captured dark page.
"""
(HERE / "DESIGN.md").write_text(body)
print("wrote DESIGN.md")
