#!/usr/bin/env python3
"""Write raw/component-tokens.json: the token tree tools/build_tokens.py resolves.

    python3 tools/build_component_tokens.py

Expedia's stylesheets (EGDS + UITK, read from live travel-assets.com CSS over
the Wayback-snapshotted pages) are machine-regular, so this tree is generated,
not hand-curated:

  color.palette.<key>     every --<key>__<role> literal declared on :root:
                          the 57-colour role palettes for light-1, dark-1,
                          dark-2, marketing-1..3, bright-1, ai-local-1, romie
                          and the eight global-loyalty tiers (css-vars.json,
                          owner "palette")
  type / typography       --egds-type-style-*: fontName, fontWeight and the
                          per-size fontSize / lineHeight / tracking for the
                          display, headline and text styles, plus composed
                          typography.* leaves
  font / typographyLegacy the older --font__* and --typography__* scales
  spacing / sizing        --spacing__*, --sizing__* and the --egds-spacing-*
                          aliases onto the standard scale
  radius / elevation      --corner_radius__*, --elevation__*
  opacity / duration / easing / motion
  component.<comp>        the remaining --<comp>__* component variables
                          (button, card, input, badge, ...), one token per
                          declaration, typed by its resolved value
  misc                    the seven plain --x names
  measured                values read off components in
                          raw/components-computed.json (measure.mjs)

The themed sets light/dark/dark-2/marketing-3/bright-1 each hold every
--egds-* semantic name, resolved on a [data-theme-*="<id>"] root by
build_tokens.py; a leaf whose resolved value equals a palette token aliases
into color.palette. A value DTCG cannot carry (gradients, url()s, keyword
strings) lands in "other" tokens or $extensions.notTokenised.
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent.parent
RAW = HERE / "raw"
V = json.loads((RAW / "css-vars.json").read_text())
COMP = json.loads((RAW / "components-computed.json").read_text())
RES = V["resolved"]
BASE = RES["light-1"]

# theme id -> token set name
THEMES = {"light": "light-1", "dark": "dark-1", "dark2": "dark-2", "marketing3": "marketing-3", "bright1": "bright-1"}

# palette keys as they appear inside --<key>__<role> names -> token key
PAL = {"light_1": "light1", "dark_1": "dark1", "dark_2": "dark2",
       "marketing_1": "marketing1", "marketing_2": "marketing2", "marketing_3": "marketing3",
       "bright_1": "bright1", "ai_local_1": "aiLocal1", "romie": "romie"}
LOYALTY = re.compile(r"--global_loyalty_([a-z_]+?)__")


def kind_of(v):
    v = v.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)|hsla?\([^)]*\)|(?:ok)?l(?:ab|ch)\([^)]*\)|color\([^)]*\)|transparent", v):
        return "color"
    if re.fullmatch(r"-?\d*\.?\d+(px|rem|em)", v):
        return "dimension"
    if re.fullmatch(r"[\d.]+m?s", v):
        return "duration"
    if re.match(r"cubic-bezier\(", v):
        return "cubicBezier"
    if re.fullmatch(r"-?\d*\.?\d+", v):
        return "number"
    if re.fullmatch(r"[\d.]+%", v):
        return "percent"
    if re.fullmatch(r"(-?\d*\.?\d+(px|rem|em)\s+){1,3}-?\d*\.?\d+(px|rem|em)\s+(rgba?\([^)]*\)|#[0-9a-fA-F]{3,8}|transparent)", v) or \
       re.fullmatch(r"(inset\s+)?(-?\d*\.?\d+(px|rem|em)\s+){0,4}(rgba?\([^)]*\)|#[0-9a-fA-F]{3,8})", v):
        return "shadow"
    return "other"


def leaf(var, ty=None, source=None, description=None):
    n = {"var": var, "type": ty or kind_of(BASE.get(var, ""))}
    if source:
        n["source"] = source
    if description:
        n["description"] = description
    return n


def camel(s):
    return re.sub(r"[-_]([a-z0-9])", lambda m: m.group(1).upper(), s)


out = {"_about": "Generated by tools/build_component_tokens.py from raw/css-vars.json and raw/components-computed.json; resolved into tokens.json by tools/build_tokens.py. Edit the builder, never this file.",
       "core": {}, "light": {}, "dark": {}, "dark2": {}, "marketing3": {}, "bright1": {}}
core = out["core"]
names = sorted(BASE)

# ---- palette: every --<key>__<role> literal ---------------------------------
palette = {}
for n in names:
    m = LOYALTY.match(n)
    if m:
        tier = camel(m.group(1).replace("_bright", "Bright"))
        role = camel(n[m.end():])
        palette.setdefault("loyalty", {}).setdefault(tier, {})[role] = leaf(n, "color")
        continue
    m = re.match(r"--(\w+?)__(\w+)$", n)
    if m and m.group(1) in PAL:
        palette.setdefault(PAL[m.group(1)], {})[camel(m.group(2))] = leaf(n, "color")
palette["$description"] = ("The literal role palettes every EGDS theme binds: 57 colours each (primary/secondary/tertiary, "
                           "containers and variants, on- colours, surfaces at three elevations, outline, scrim/shadow and the "
                           "status set critical/positive/featured/info). [data-theme-light|dark] rebinds the --egds-* semantic "
                           "names to one of these; light1 is the signed-out page theme.")
core["color"] = {"palette": palette,
                 "$description": "Every colour literal the stylesheets declare lives here; the themed sets hold the --egds-* semantic roles that alias into it."}

# ---- egds type styles -------------------------------------------------------
TYPE = {}
TYPE_RE = re.compile(r"--egds-type-style-(display|headline|text)(?:-([a-z-]+))?-(font-name|font-weight|font-size|line-height|line-height-variant|font-tracking)$")
for n in names:
    m = TYPE_RE.match(n)
    if not m:
        continue
    style, size, part = m.groups()
    key = {"font-name": "fontFamily", "font-weight": "fontWeight", "font-size": "fontSize",
           "line-height": "lineHeight", "line-height-variant": "lineHeightVariant", "font-tracking": "letterSpacing"}[part]
    # camel the parsed size ("extra-large" -> "extraLarge") so it matches the
    # size names the composed typography.* block below asks for.
    node = TYPE.setdefault(style, {}) if not size else TYPE.setdefault(style, {}).setdefault(camel(size), {})
    ty = {"fontFamily": "fontFamily", "fontWeight": "fontWeight"}.get(key, "dimension")
    node[key] = leaf(n, ty)
TYPE["$description"] = ("The --egds-type-style-* declarations: display is Reckless XPD, headline and text are Centra No2. "
                        "display has small/medium sizes, headline small/medium/large/extra-large/overline, text small/medium/large "
                        "(each with a variant line-height).")
core["type"] = TYPE

comp_t = {}
for style, sizes in (("display", ("small", "medium")),
                     ("headline", ("small", "medium", "large", "extraLarge", "overline")),
                     ("text", ("small", "medium", "large"))):
    for size in sizes:
        if size not in TYPE.get(style, {}):
            continue
        comp_t[f"{style}-{size}"] = {"type": "typography", "value": {
            "fontFamily": "{type.%s.fontFamily}" % style,
            "fontSize": "{type.%s.%s.fontSize}" % (style, size),
            "lineHeight": "{type.%s.%s.lineHeight}" % (style, size),
            "fontWeight": "{type.%s.fontWeight}" % style,
            "letterSpacing": "{type.%s.%s.letterSpacing}" % (style, size)},
            "source": "composed from the --egds-type-style-%s-* declarations" % style}
comp_t["$description"] = "Composed type styles (EGDS type-style): use these for text, not the raw pieces."
core["typography"] = comp_t

# ---- older font / typography scales -----------------------------------------
def dim_names(prefix, group, desc):
    g = {}
    for n in names:
        if n.startswith(prefix):
            g[camel(n[len(prefix):])] = leaf(n)
    if g:
        g["$description"] = desc
        core[group] = g

dim_names("--font__", "font", "The older --font__* scale (numeric size x weight names, stacks and line-heights), still declared on :root.")
dim_names("--typography__", "typographyLegacy", "The older --typography__* display/body/utility scale, still declared on :root.")
dim_names("--type__", "typeScale", "The --type__scale-* size and decoration names.")

# ---- scales -----------------------------------------------------------------
dim_names("--spacing__", "spacing", "The --spacing__* step scale (0x..24x and halves); --egds-spacing-* aliases into it via --standard__spacing__*.")
dim_names("--sizing__", "sizing", "The --sizing__* step scale (0x..128x, quarters and halves).")
dim_names("--corner_radius__", "radius", "The --corner_radius__* scale: 0x, 1x (4px), 2x, 4x, 6x, 8x, 12x, 10000x (pill).")
dim_names("--elevation__", "elevation", "The --elevation__* box-shadow steps.")
dim_names("--opacity__", "opacity", "The --opacity__* steps; percent values become the number they mean (disabled 0.4).")
dim_names("--duration__", "duration", "The --duration__* enter/exit/standard steps.")
dim_names("--easing__", "easing", "The --easing__* keyword easings (enter ease-out, exit ease-in, standard ease).")
for _k in list(core.get("easing", {})):
    if not _k.startswith("$"):
        core["easing"][_k]["type"] = "cubicBezier"
dim_names("--font_face__", "fontFace", "The --font_face__* family stacks (Centra No2, Reckless XPD) EGDS declares per role.")
dim_names("--standard__", "standard", "The --standard__* binding layer: the standard theme's spacing/font assignments the --egds-spacing-* and type roles read through.")

# egds spacing aliases + egds non-semantic names that are not theme-bound
spacing_egds = {}
for n in names:
    if n.startswith("--egds-spacing-"):
        spacing_egds[camel(n[len("--egds-spacing-"):])] = leaf(n)
if spacing_egds:
    spacing_egds["$description"] = "The --egds-spacing-* semantic names, aliases onto spacing.* through --standard__spacing__*."
    core.setdefault("spacing", {}).update(spacing_egds)

motion = {}
for n in names:
    if n.startswith(("--egds-movement-", "--egds-appearance-")):
        motion[camel(n[7:])] = leaf(n, "other")
if motion:
    motion["$description"] = "Movement/appearance presets: a duration plus a cubic-bezier, kept as the raw string (DTCG transition carries no string pair)."
    core["motion"] = motion

# ---- remaining component variables ------------------------------------------
SKIP = re.compile(r"--(egds-|spacing__|sizing__|corner_radius__|elevation__|opacity__|duration__|easing__|standard__|font__|font_face__|typography__|type__|global_loyalty_|animate-|background-position|slider-|touch-target)")
comp = {}
for n in names:
    if SKIP.match(n):
        continue
    m = re.match(r"--(\w+?)__(\w+)$", n)
    if not m or m.group(1) in PAL:
        continue
    c, rest = camel(m.group(1)), camel(m.group(2))
    node = comp.setdefault(c, {})
    node[rest] = leaf(n)
for c in comp:
    comp[c]["$description"] = "The --%s__* component variables, resolved on :root (overrides such as .elicitation are noted in source)." % c
core["component"] = comp
core["component"]["$description"] = ("Per-component variables EGDS declares (--button__corner_radius 2500rem pill, --card__corner_radius 1rem, "
                                     "--input__corner_radius 0.5rem, the elevation and scrim names): one token per declaration, typed by resolved value.")

misc = {}
for n in names:
    if "__" not in n and not n.startswith("--egds-"):
        misc[camel(n[2:])] = leaf(n, "other")
if misc:
    misc["$description"] = "Plain custom properties with no family prefix."
    core["misc"] = misc

# ---- themed sets: every --egds-* semantic name ------------------------------
for setname in THEMES:
    tree = {}
    for n in names:
        if not n.startswith("--egds-") or n.startswith("--egds-type-style-"):
            continue
        ty = kind_of(RES[THEMES[setname]].get(n, ""))
        tree[camel(n[7:])] = leaf(n, ty)
    out[setname]["egds"] = tree
    out[setname]["egds"]["$description"] = "The --egds-* semantic roles resolved on data-theme-*=%s" % THEMES[setname]

# ---- measured values ---------------------------------------------------------
measured = {}


GAPS = out.setdefault("_gaps", [])


def grab(comp, state="default"):
    """The reading for comp in state. A missing component or state stops the build: falling back
    to another state would publish, say, the default outline as the focus ring under a
    `measured <comp> <state>` source."""
    c = COMP["components"].get(comp)
    if not c or state not in c.get("states", {}):
        raise SystemExit(f"{comp} {state}: no such reading in raw/components-computed.json; fix the row or recapture")
    if c.get("missing"):
        # measure.mjs keeps an earlier run's states when the component is not found again
        raise SystemExit(f"{comp}: flagged missing by the last capture; its states are an earlier run's, recapture it")
    st = c["states"][state]
    if "style" not in st or st.get("skipped") or st.get("via") == "focus failed":
        raise SystemExit(f"{comp} {state}: no usable reading ({st.get('skipped') or st.get('error') or st.get('via')})")
    return st, c


def m_dimension(path, comp, state, pick, desc):
    st, c = grab(comp, state)
    s = st.get("style", {})
    v = pick(st, s)
    if v is None:
        raise SystemExit(f"{comp} {state}: the reading has no value for core.measured.{'.'.join(path)}")
    node = measured
    for k in path[:-1]:
        node = node.setdefault(k, {})
    node[path[-1]] = {"type": "dimension", "value": v,
                      "source": f"measured {comp} {state} ({c.get('page')}, raw/components-computed.json)",
                      "description": desc}


UA_RING = "rgb(16, 16, 16)"  # Chrome's own -webkit-focus-ring-color


def m_color(path, comp, state, pick, desc, optional=False):
    """A measured colour. A missing value stops the build unless the row is optional (a lookup that
    may find nothing); a transparent or `none` reading is recorded as a gap."""
    st, c = grab(comp, state)
    s = st.get("style", {})
    v = pick(st, s)
    if v is None and not optional:
        raise SystemExit(f"{comp} {state}: the reading has no value for core.measured.{'.'.join(path)}")
    if not v or v in ("none", "rgba(0, 0, 0, 0)"):
        GAPS.append({"token": "core.measured." + ".".join(path), "why": f"{comp} {state} paints no colour there ({v!r})"})
        return
    if path[-1] == "outlineColor" and s.get("outlineStyle") == "auto" and v == UA_RING:
        # an `auto` outline in Chrome's own ring colour is the browser default, not egds-outline-focus
        GAPS.append({"token": "core.measured." + ".".join(path), "why": f"{comp} {state} draws the browser's default focus ring "
                     f"(outline {s.get('outlineWidth')} auto {v}); the declared --egds-outline-focus is not what paints"})
        return
    node = measured
    for k in path[:-1]:
        node = node.setdefault(k, {})
    node[path[-1]] = {"type": "color", "value": v,
                      "source": f"measured {comp} {state} ({c.get('page')}, raw/components-computed.json)",
                      "description": desc}


def m_text(path, comp, state, key, desc):
    st, c = grab(comp, state)
    ts = st.get("textStyle") or st.get("style", {})
    v = ts.get(key)
    if v is None:
        raise SystemExit(f"{comp} {state}: no {key} in its reading")
    node = measured
    for k in path[:-1]:
        node = node.setdefault(k, {})
    ty = "fontWeight" if key == "fontWeight" else "dimension"
    node[path[-1]] = {"type": ty, "value": v,
                      "source": f"measured {comp} {state} ({c.get('page')}, raw/components-computed.json)",
                      "description": desc}


m_dimension(["header", "height"], "header", "default", lambda st, s: st["rect"]["h"], "Top bar height.")
m_dimension(["field", "height"], "field-destination", "default", lambda st, s: st["rect"]["h"], "Search field height.")
m_dimension(["button", "search", "height"], "search-submit", "default", lambda st, s: st["rect"]["h"], "Search button height.")
m_dimension(["button", "search", "radius"], "search-submit", "default", lambda st, s: s.get("borderTopLeftRadius"), "Search button corner radius (the 2500rem pill resolves here).")
m_dimension(["button", "tertiary", "height"], "tertiary-button", "default", lambda st, s: st["rect"]["h"], "Tertiary button height (medium uitk-button).")
m_dimension(["card", "radius"], "property-card", "default", lambda st, s: s.get("borderTopLeftRadius"), "Result card corner radius (card__corner_radius).")
m_dimension(["dialog", "radius"], "calendar-dialog", "open", lambda st, s: s.get("borderTopLeftRadius"), "Dialog (calendar) corner radius.")
m_dimension(["pill", "radius"], "sort-control", "default", lambda st, s: s.get("borderTopLeftRadius"), "Pill corner radius (the sort uitk-pill).")
m_dimension(["tab", "height"], "tab", "default", lambda st, s: st["rect"]["h"], "Product tab height in the search form.")
m_dimension(["heart", "size"], "card-heart", "default", lambda st, s: st["rect"]["w"], "Save-heart button size.")
m_dimension(["focus", "outlineWidth"], "search-submit", "focus-visible", lambda st, s: s.get("outlineWidth"), "Focus ring width on keyboard focus.")
m_color(["focus", "outlineColor"], "search-submit", "focus-visible", lambda st, s: s.get("outlineColor"), "Focus ring colour.")
m_color(["button", "search", "background"], "search-submit", "default", lambda st, s: s.get("backgroundColor"), "Search button fill (egds-primary).")
m_color(["button", "search", "text"], "search-submit", "default", lambda st, s: s.get("color"), "Text on the search button (egds-on-primary).")
m_color(["page", "background"], "search-shell", "default", lambda st, s: st.get("ancestors", [{}])[0].get("bg") if st.get("ancestors") else None, "Ground behind the search shell.", optional=True)
m_text(["type", "heroTitle", "fontSize"], "hero-title", "default", "fontSize", "Hero display size at 1440.")
m_text(["type", "heroTitle", "lineHeight"], "hero-title", "default", "lineHeight", "Hero display line-height.")
m_text(["type", "heroTitle", "fontWeight"], "hero-title", "default", "fontWeight", "Hero display weight.")
m_text(["type", "body", "fontSize"], "amenity-item", "default", "fontSize", "Card amenity text size.")
m_text(["type", "priceNightly", "fontSize"], "price-block", "default", "fontSize", "Nightly price size on a card.")
m_dimension(["mobile", "field", "height"], "m-field", "default", lambda st, s: st["rect"]["h"], "Search field height at 390 wide.")
measured["$description"] = "Values that are not one variable, measured on components in raw/components-computed.json; each names the component and state."
core["measured"] = measured

(RAW / "component-tokens.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")


def count(d):
    return sum(count(v) for k, v in d.items() if not k.startswith("$")) if isinstance(d, dict) and "$value" not in d and "type" not in d else 1 if isinstance(d, dict) else 0


print({k: count(v) for k, v in out.items() if not k.startswith("_")}, "->", RAW / "component-tokens.json")
