export async function patch(context) {
  // bot check: recorded as a boundary, not bypassed. navigator.webdriver is
  // left as the browser reports it; an earlier version masked it.
  await context.addInitScript(() => {
    try { window.__captureDPR = window.devicePixelRatio; } catch { /* read-only */ }
  });
}

export async function launch({ width = 1440, height = 900, mobile = false } = {}) {
  const browser = await chromium.launch();
  const context = await browser.newContext(mobile
    ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, userAgent: UA_MOBILE, isMobile: true, hasTouch: true, locale: 'en-US' }
    : { viewport: { width, height }, deviceScaleFactor: 2, userAgent: UA, locale: 'en-US', reducedMotion: 'no-preference' });
  await patch(context);
  return { browser, context };
}

export async function clearChallenge(page, { tries = 8, step = 1500 } = {}) {
  for (let i = 0; i < tries; i++) {
    const s = await page.evaluate(() => ({
      title: document.title,
      body: (document.body && document.body.innerText || '').slice(0, 400),
    })).catch(() => ({ title: '', body: '' }));
    const challenging = /just a moment/i.test(s.title)
      || /performing security verification|verify you are human|verifying you are human|checking your browser/i.test(s.body);
    if (!challenging && s.body.length > 40) return true;
    await page.waitForTimeout(step);
  }
  return false;
}

// Hide consent and promo overlays. Never click a consent control.
export async function closePromo(page) {
  for (let i = 0; i < 3; i++) {
    const hit = await page.evaluate(() => {
      let n = 0;
      const hide = (el) => {
        if (!el || el.getAttribute('data-m-hidden-overlay')) return;
        el.setAttribute('data-m-hidden-overlay', '1');
        el.style.setProperty('display', 'none', 'important');
        n++;
      };
      for (const sel of [
        '#onetrust-banner-sdk', '#onetrust-consent-sdk', '#onetrust-pc-sdk',
        '[id*="cookie-banner"]', '[id*="CookieBanner"]',
        '[class*="cookie-banner"]', '[class*="CookieBanner"]',
        '[aria-label="Cookie preferences"]',
      ]) {
        document.querySelectorAll(sel).forEach(hide);
      }
      for (const el of document.querySelectorAll('div,section,aside,[role="dialog"],[role="alertdialog"]')) {
        const t = (el.innerText || '').slice(0, 900);
        const r = el.getBoundingClientRect();
        const cs = getComputedStyle(el);
        if ((cs.position === 'fixed' || cs.position === 'sticky')
          && /cookie|consent|we value your privacy|privacy preference/i.test(t)
          && t.length < 1800 && r.height > 40 && r.height < 720 && r.width > 180) hide(el);
      }
      // A dismissible announcement strip is hidden, never answered.
      const banner = [...document.querySelectorAll('button')].find((b) => /dismiss banner/i.test(b.getAttribute('aria-label') || b.innerText || ''));
      if (banner) {
        const host = banner.closest('[role="region"], [class*="banner"], section, div') || banner.parentElement;
        if (host && host.getBoundingClientRect().height < 160) hide(host);
      }
      document.body && document.body.style.removeProperty('overflow');
      document.documentElement && document.documentElement.style.removeProperty('overflow');
      return n;
    }).catch(() => 0);
    if (!hit) break;
    await page.waitForTimeout(400);
  }
  return true;
}

// Navigation errors throw, and a challenge page that never clears throws, so
// a timed-out or blocked page is never measured and saved as the product.
export async function open(page, url, { wait = 5000, promo = 'close' } = {}) {
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 90000 });
  if (!(await clearChallenge(page))) throw new Error(`bot check did not clear on ${url}: recorded as a boundary, not bypassed`);
  await page.waitForTimeout(wait);
  if (promo === 'close') await closePromo(page);
}

